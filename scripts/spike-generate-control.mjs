/**
 * THROWAWAY spike script -- generates the "control" sample PDF via a
 * different code path than scripts/spike-generate-samples.mjs (which uses
 * pdfkit, a low-level PDF writer). This one uses Playwright's already-
 * installed Chromium to print HTML to PDF, approximating a Google-Docs- or
 * browser-print-style export. Fictional content only (CLAUDE.md Rule 22).
 *
 * Run: node scripts/spike-generate-control.mjs
 */
import { chromium } from "playwright";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.join(__dirname, "..", "scratch", "pdf-samples");
fs.mkdirSync(OUT_DIR, { recursive: true });

const html = `
<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<style>
  body { font-family: Georgia, serif; margin: 60px; color: #111; }
  h1 { font-size: 26px; }
  h2 { font-size: 18px; margin-top: 28px; }
  p { font-size: 12px; line-height: 1.5; }
</style>
</head>
<body>
  <h1>Mele Tupou's Working Holiday Notes</h1>
  <h2>Settling In</h2>
  <p>
    This is a fictional account written only to test a PDF-import spike. A made-up traveller,
    Mele Tupou, spent a season working at a fictional cafe in a town called Fernbrook, and these
    notes describe the first few weeks of that invented placement.
  </p>
  <p>
    Nothing in this document refers to a real person, business, or event -- it exists purely to
    give the extraction spike a "browser print" style control sample, generated by Chromium's own
    PDF printer rather than a PDF-writing library.
  </p>
  <h2>A Typical Week</h2>
  <p>
    Shifts ran early mornings, six days a week, with a fictional day off reserved for exploring
    nearby trails. The rest of this paragraph is filler text to give the extractor more than one
    paragraph of body copy to work with under this heading.
  </p>
</body>
</html>
`;

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent(html, { waitUntil: "networkidle" });
await page.pdf({
  path: path.join(OUT_DIR, "control-browser-print.pdf"),
  format: "A4",
});
await browser.close();

console.log(`Control PDF written to ${OUT_DIR}/control-browser-print.pdf`);
